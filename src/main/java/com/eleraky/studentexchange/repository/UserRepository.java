package com.eleraky.studentexchange.repository;

// ============================================================
// نستورد الكيان User للتعامل معه
// ============================================================
import com.eleraky.studentexchange.model.User;

// ============================================================
// JpaRepository: واجهة من Spring Data JPA
// توفر عمليات CRUD الأساسية تلقائياً (حفظ، بحث، حذف، تحديث)
// ============================================================
import org.springframework.data.jpa.repository.JpaRepository;

// ============================================================
// @Repository: تخبر Spring أن هذه الواجهة هي Repository
// Spring سينشئ Implementation تلقائياً في وقت التشغيل
// ============================================================
import org.springframework.stereotype.Repository;

// ============================================================
// Optional: من Java 8 - لتجنب NullPointerException
// يمكن أن تحتوي على قيمة أو تكون فارغة بطريقة آمنة
// ============================================================
import java.util.Optional;

@Repository  // نحدد أن هذا Repository
public interface UserRepository extends JpaRepository<User, Long> {
    // ============================================================
    // User: الكيان الذي نتعامل معه
    // Long: نوع المفتاح الأساسي (ID)
    // ============================================================
    // JpaRepository يوفر تلقائياً هذه الدوال:
    // - save(User user): حفظ مستخدم جديد أو تحديث موجود
    // - findById(Long id): البحث عن مستخدم بالـ ID
    // - findAll(): جلب جميع المستخدمين
    // - deleteById(Long id): حذف مستخدم
    // - count(): عدد المستخدمين
    // - existsById(Long id): التحقق من وجود مستخدم
    // ============================================================

    // ============================================================
    // دوال مخصصة (Custom Queries):
    // Spring Data JPA سينشئ الاستعلام تلقائياً من اسم الدالة!
    // ============================================================

    // ============================================================
    // findByUsername: ابحث عن مستخدم باسم المستخدم
    // Optional<User>: قد يوجد مستخدم أو لا يوجد
    // Spring سينشئ SQL: SELECT * FROM users WHERE username = ?
    // ============================================================
    Optional<User> findByUsername(String username);

    // ============================================================
    // findByEmail: ابحث عن مستخدم بالبريد الإلكتروني
    // ============================================================
    Optional<User> findByEmail(String email);

    // ============================================================
    // existsByUsername: هل يوجد مستخدم بهذا الاسم؟
    // Boolean: true أو false
    // أسرع من findByUsername لأنها لا تجلب كل البيانات
    // ============================================================
    Boolean existsByUsername(String username);

    // ============================================================
    // existsByEmail: هل يوجد مستخدم بهذا البريد؟
    // ============================================================
    Boolean existsByEmail(String email);

}